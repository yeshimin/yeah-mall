  `update_by` varchar(32) NOT NULL DEFAULT '' COMMENT '更新者',
  `mch_id` bigint(20) NOT NULL COMMENT '商户ID',
  `shop_id` bigint(20) NOT NULL COMMENT '店铺ID',
